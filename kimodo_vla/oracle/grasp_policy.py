"""Blocking box grasp on the frozen Kimodo + SONIC backend.

Every round latches the box pose once, waits a fixed delay, then walks to a stance in front
of the box, brings an open hand to either side, lets the simulator-side gate close both
hands once the wrists have arrived, squeezes the box between the two fists, and lifts.
Nothing about the box is read again before the next round. Walking is generated by Kimodo
as whole clips along a root path; everything from the stance on reuses the standing IK-hold
backend.
"""
from dataclasses import dataclass, field
import json
import time

import numpy as np
import torch
from scipy.spatial.transform import Rotation, Slerp

from kimodo_vla.core.types import G1_JOINT_NAMES, yaw_matrix, yaw_of
from kimodo_vla.model.native_policy import ConstraintGuidance
from kimodo_vla.model.planner import _episode_noise_seed
from kimodo_vla.motion.g1_reference import _interpolate_motion
from .continuity import blend_reference, bounded_hinge_trajectory
from .geometry import BASIS, Frame, rotation_wxyz
from .policy import OraclePolicy
from .support import support_channels

STANDING = ('raise', 'advance', 'grip', 'squeeze', 'lift', 'hold', 'release')


def smooth(u):
    u = np.clip(u, 0., 1.)
    return u**3 * (10 - 15*u + 6*u*u)


def face_yaw(quat_wxyz):
    """Yaw of the box face nearest to world +x, in (-45, 45] degrees expressed in radians."""
    yaw = float(yaw_of(rotation_wxyz(quat_wxyz)))
    return (yaw + np.pi/4) % (np.pi/2) - np.pi/4


def stance(box_pos, cfg):
    """Root position squarely in front of the box; heading stays +x.

    The wrists end up ``stance_reach_m`` ahead of the root wherever the box lies on the table,
    because SONIC gives way under a long reach; the root never comes closer to the table edge
    than ``stance_clearance_m``. Every ``box_pos`` in this module is the box's centre of mass,
    not the origin of its asset, which lies on the bottom face.
    """
    wrist_x = box_pos[0] + cfg['grip_forward_m'] - cfg['fist_centre_m'] * np.cos(np.radians(cfg['wrist_pitch_down_deg']))
    return np.array([min(wrist_x - cfg['stance_reach_m'], cfg['table_edge_x_m'] - cfg['stance_clearance_m']), box_pos[1]])


def half_width(yaw, half, x):
    """Half extent along y of a square box turned by ``yaw``, on the line ``x`` ahead of its centre."""
    c, s = abs(np.cos(yaw)), abs(np.sin(yaw))
    corners = [(c*a - s*b, s*a + c*b) for a, b in ((half, half), (half, -half), (-half, half), (-half, -half))]
    widest = 0.
    for i, (x0, y0) in enumerate(corners):
        for x1, y1 in corners[i + 1:]:
            if not min(x0, x1) - 1e-12 <= x <= max(x0, x1) + 1e-12:
                continue
            if abs(x1 - x0) < 1e-12:
                widest = max(widest, abs(y0), abs(y1))
            else:
                widest = max(widest, abs(y0 + (x - x0) / (x1 - x0) * (y1 - y0)))
    return float(widest)


def graspable(box_pos, box_quat, cfg):
    """The box still stands on the table where two hands can reach its sides from the edge."""
    up = rotation_wxyz(box_quat)[2, 2]
    low, high = cfg['graspable_height_m']
    return bool(low <= box_pos[2] <= high and abs(up) > .9
                and box_pos[0] - cfg['table_edge_x_m'] <= cfg['graspable_depth_m'])


def waypoints(box_pos, box_quat, root_xy, cfg):
    """Wrist poses [left, right] of one attempt, in world coordinates with the robot facing +x.

    The left palm faces -y of its wrist frame and the right palm +y, so two level wrists act
    as parallel jaws along world y. The hands arrive open and only as wide as they must: the
    fingers pass the box at its widest line, and the open thumb, which points at the other
    hand from just ahead of the wrist, passes it where a turned box is already narrower. They
    close there, beside the box, and the two fists then press just beyond its widest line. Closing fingers that already press on the
    box sweeps it out of the grasp, and fists that press before the widest line wedge a
    turned box away; pressing slightly beyond it pushes the box into the hands instead, so the
    wrists aim there and a wrist that stops short still lands on the line. A box that is not
    square to the jaws is turned square by the squeeze.
    """
    box = np.asarray(box_pos, dtype=float)
    pitch = np.radians(cfg['wrist_pitch_down_deg'])
    rotation = Rotation.from_euler('y', pitch).as_matrix()
    half = cfg['box_half_m']
    yaw = face_yaw(box_quat)
    extent = half * (abs(np.cos(yaw)) + abs(np.sin(yaw)))
    # A square box can be pressed anywhere along its faces; only a turned one needs the fists
    # beyond its widest line, and every centimetre not reached for helps SONIC arrive.
    low, high = np.radians(cfg['grip_forward_yaw_deg'])
    forward = cfg['grip_forward_m'] * float(np.clip((abs(yaw) - low) / (high - low), 0., 1.))
    centre = box + [forward - cfg['fist_centre_m'] * np.cos(pitch), 0,
                    cfg['grip_height_m'] + cfg['fist_centre_m'] * np.sin(pitch)]

    def wrists(half_width, lift=0.):
        return np.array([centre + [0, sign * half_width, lift] for sign in (1, -1)])

    thumb_x = centre[0] + cfg['thumb_forward_m'] - box[0]
    opening = max(extent + cfg['palm_offset_m'], half_width(yaw, half, thumb_x) + cfg['thumb_reach_m']) + cfg['open_clearance_m']
    pre = wrists(opening)
    via = pre.copy()
    via[:, 0] = np.minimum(pre[:, 0], root_xy[0] + cfg['via_forward_m'])
    via[:, 2] += cfg['via_raise_m']
    squeeze = half + cfg['fist_offset_m'] - cfg['squeeze_m']
    # On the way up the fingers keep pointing down, so that they do not swing out under the
    # table edge; the hands level off only while they advance above the table.
    raised = Rotation.from_euler('y', np.radians(cfg['via_pitch_down_deg'])).as_matrix()
    return {'via': via, 'pre': pre, 'squeeze': wrists(squeeze), 'lift': wrists(squeeze, cfg['lift_m']),
            'rotation': np.stack([rotation, rotation]), 'via_rotation': np.stack([raised, raised]),
            'opening_m': float(opening), 'face_yaw_rad': yaw, 'grip_forward_m': forward}


def clip_profile(reach, arrive, frames=50, stop_frame=40, ease_frames=15):
    """Distance along the line at each canvas frame of one walking clip.

    A clip that reaches its goal eases in and out and stands from ``stop_frame`` on. A clip
    that cannot reach it eases in and then keeps walking at a steady pace to the last frame.
    """
    k = np.arange(frames, dtype=float)
    if arrive:
        return reach * smooth(k / stop_frame)
    # constant speed after an ease-in whose average speed is half the final speed
    cruise = reach / (frames - 1 - ease_frames / 2)
    return np.where(k < ease_frames, cruise * k**2 / (2 * ease_frames), cruise * (k - ease_frames / 2))


class WristPath:
    """Piecewise wrist poses over simulation time; holds the last pose after its end."""
    def __init__(self, time, positions, rotations):
        self.pieces = []
        self.end = (float(time), np.asarray(positions, dtype=float), np.asarray(rotations, dtype=float))

    def to(self, positions, rotations, duration, start=None):
        t0 = self.end[0] if start is None else max(float(start), self.end[0])
        if t0 > self.end[0]:
            self.pieces.append((self.end[0], t0, self.end[1], self.end[2], self.end[1], self.end[2]))
        target = (t0 + duration, np.asarray(positions, dtype=float), np.asarray(rotations, dtype=float))
        self.pieces.append((t0, target[0], self.end[1], self.end[2], target[1], target[2]))
        self.end = target
        return target[0]

    def __call__(self, time):
        """Positions [2, 3] and rotations [2, 3, 3] at one simulation time."""
        if not self.pieces or time >= self.end[0]:
            return self.end[1].copy(), self.end[2].copy()
        for t0, t1, p0, r0, p1, r1 in self.pieces:
            if time < t1:
                w = float(np.clip(smooth((time - t0) / (t1 - t0)), 0., 1.))
                rot = np.stack([Slerp([0, 1], Rotation.from_matrix([a, b]))(w).as_matrix() for a, b in zip(r0, r1)])
                return p0 + w * (p1 - p0), rot
        raise AssertionError('unreachable')

    def piece_end(self, time):
        return next((t1 for _, t1, *_ in self.pieces if time < t1), self.end[0])


@dataclass
class Round:
    index: int
    latch_time: float
    box_pos: list
    box_quat: list
    phase: str = 'wait'
    phase_time: float = 0.
    graspable: bool = True
    event: dict | None = None
    notes: dict = field(default_factory=dict)


class BoxGraspPolicy(OraclePolicy):
    def __init__(self, *args, config, latch_delay_steps=75, stand_still=False, **kwargs):
        self.cfg = json.loads(open(config).read()) if not isinstance(config, dict) else config
        if latch_delay_steps < 0:
            raise ValueError('Latch delay cannot be negative')
        self.latch_delay = int(latch_delay_steps)
        # Off by default. On, the robot never walks: every round reaches from where it stands.
        self.stand_still = bool(stand_still)
        super().__init__(*args, **kwargs)
        if self.mode != 'hold' or self.trajectory_projection != 'ik-hold' or self.variant != 'bounded':
            raise ValueError('The grasp loop needs the bounded standing IK-hold backend')

    def reset(self, seed=None):
        self.round = self.path = self.episode_heading = self.walk = None
        return super().reset(seed)

    # ---- episode and round bookkeeping -------------------------------------------------
    def begin_episode(self, first):
        rotation = rotation_wxyz(first['root_quat'])
        self.episode_heading = yaw_matrix(float(yaw_of(rotation)))
        self.stand = {'joints': np.asarray(first['joints']), 'root_height': first['root_pos'][2],
                      'rotation': self.episode_heading.T @ rotation}
        self.frame, self.start_time = Frame(first['root_pos'], self.episode_heading), first['time']
        self.target_info = {'mode': 'box-grasp', 'targets_world': np.repeat(np.asarray(first['wrist_pos'])[:, None], 2, 1).tolist(),
                            'wrist_rotation_world': first['wrist_rot'], 'arrival_time': first['time']}
        self.begin_round(first)

    def begin_round(self, sample):
        index = 0 if self.round is None else self.round.index + 1
        self.round = Round(index, sample['time'], list(sample['box_com']), list(sample['box_quat']),
                           phase_time=sample['time'])
        self.round.graspable = graspable(sample['box_com'], sample['box_quat'], self.cfg)
        self.log('latch', graspable=self.round.graspable)

    def enter(self, phase, time):
        self.round.phase, self.round.phase_time = phase, time
        self.log('phase')

    def log(self, kind, **extra):
        r = self.round
        with (self.run / 'rounds.jsonl').open('a') as f:
            f.write(json.dumps({'kind': kind, 'round': r.index, 'phase': r.phase, 'time': r.phase_time,
                'latch_time': r.latch_time, 'box_pos': r.box_pos, 'box_quat': r.box_quat, **r.notes, **extra}) + '\n')

    def grasp_info(self):
        r = self.round
        return {'round': r.index, 'phase': r.phase, 'latch_time': r.latch_time,
                'latched_box_pos': r.box_pos, 'latched_box_quat': r.box_quat, 'graspable': r.graspable,
                'hands': 'gate' if r.phase in ('advance', 'grip', 'squeeze', 'lift', 'hold') else 'open',
                'event': r.event if r.phase == 'advance' else None}

    # ---- motion primitives -------------------------------------------------------------
    def remember(self, samples):
        if self.history and samples[0]['time'] <= self.history[-1]['time']:
            raise ValueError('Non-monotonic oracle history')
        self.history.extend(samples)
        self.history = self.history[-180:]

    def hold(self, obs, count):
        """Repeat the last consumed reference: no root motion, same posture."""
        rot = self.episode_heading.T @ rotation_wxyz(obs['reference_root_quat'])
        action = np.r_[0., 0., obs['reference_root_pos'][2], rot[:, :2].ravel(), obs['reference_joints'], 0., 0.]
        return np.tile(action, (count, 1))

    def reference_features(self):
        """Kimodo features of the reference SONIC has consumed so far, in the current clip frame."""
        h = self.history
        roots = (np.asarray([x['reference_root_pos'] for x in h]) - self.frame.origin) @ self.frame.heading
        rotations = np.stack([self.frame.heading.T @ rotation_wxyz(x['reference_root_quat']) for x in h])
        first_step = int(round((h[0]['time'] - self.start_time) * 50))
        local, root = self.features.motion(np.asarray([x['reference_joints'] for x in h]), roots, rotations, first_step)
        return self.features.features(local, root)

    def root_template(self, path_world):
        """Features of the standing pose carried along a root path [T, 2], one row per canvas frame."""
        pad = 5
        path = np.concatenate((np.repeat(path_world[:1], pad, 0), path_world, np.repeat(path_world[-1:], pad, 0)))
        world = np.c_[path, np.full(len(path), self.stand['root_height'])]
        pose = self.features.codec.decode_joint_configuration_pose(np.tile(self.stand['joints'], (len(path), 1)),
            (world - self.frame.origin) @ self.frame.heading,
            root_rotation_matrices=np.tile(self.stand['rotation'], (len(path), 1, 1)), joint_names=G1_JOINT_NAMES)
        return self.features.features(pose['local_rot_mats'], pose['root_positions'])[pad:-pad]

    @torch.inference_mode()
    def walk_clip(self, obs, request):
        """One whole Kimodo clip toward the stance, executed to its end before anything is replanned.

        Replanning a gait every half second does not work with this model: each new plan starts
        several centimetres away from the pose it was conditioned on and in a different step
        phase. A clip is therefore taken as relative motion from the reference SONIC is on, and
        what remains after it is measured and handed to the next clip.
        """
        c, rep, w = self.cfg, self.model.representation, self.walk
        reference = np.asarray(obs['reference_root_pos'], dtype=float)
        self.frame, self.start_time = Frame(reference, self.episode_heading), obs['time']
        remaining = w['goal'] - np.asarray(obs['root_pos'][:2])
        distance = float(np.linalg.norm(remaining))
        # SONIC covers only part of what a clip asks for (the generated feet partly slide), and a
        # short clip is all slide. A clip that stops covers a predictable share only when it is
        # asked for a long step, so the walk passes through at pace while far away and stops
        # with one long clip from within ``walk_stop_within_m``. Whatever is asked for is more
        # than what is left, and never less than a real step. A passing clip is never the last.
        near = self.at_stance(obs)
        arrive = near or distance <= c['walk_stop_within_m'] or w['clips'] >= c['walk_max_clips'] - 1
        wanted = distance if near else max(distance * c['walk_gain'], c['walk_min_clip_m']) if arrive else c['walk_clip_m']
        reach = min(wanted, c['walk_clip_m'])
        direction = remaining / distance if distance > 1e-9 else np.zeros(2)
        path = reference[:2] + clip_profile(reach, arrive, stop_frame=c['walk_stop_frame'])[:, None] * direction
        features = self.reference_features()
        hist = features[:-1][-100:]
        known = torch.zeros_like(hist, dtype=torch.bool)
        known[-1] = True  # the pose to continue from; standing history only keeps the model standing
        values, mask = torch.zeros(50, rep.motion_rep_dim), torch.zeros(50, rep.motion_rep_dim, dtype=torch.bool)
        end = rep.slice_dict['global_rot_data'].stop
        values[0, :end], mask[0, :end] = features[-1, :end], True
        template = self.root_template(path)
        along = torch.zeros(rep.motion_rep_dim, dtype=torch.bool)
        root = rep.slice_dict['smooth_root_pos'].start
        along[[root, root + 2]] = True
        along[rep.slice_dict['global_root_heading']] = True
        standing = support_channels(rep, 'root')
        for k in range(1, 50):
            channels = standing if arrive and k >= c['walk_stop_frame'] else along
            values[k, channels], mask[k, channels] = template[k, channels], True
        # One conditional pass. The standing backend's guidance drops the whole motion mask in
        # its free pass, which pushes a walk away from an unrelated free motion.
        guided = self.model.denoiser
        self.model.denoiser = ConstraintGuidance(guided.model, 1.)
        generator = torch.Generator(device=self.model.device).manual_seed(_episode_noise_seed(self.seed, self.plan_index))
        begin = time.perf_counter()
        try:
            output = self.model.predict_future(str(request['task']).strip(), torch.zeros(1, 3, 1, 1), hist,
                history_feature_mask=known, text_feat=torch.zeros(1, 4096).to(self.model.device),
                future_condition=values, future_condition_mask=mask, diffusion_steps=self.steps, generator=generator)
        finally:
            self.model.denoiser = guided
        elapsed = time.perf_counter() - begin
        output = {k: v.cpu() if torch.is_tensor(v) else v for k, v in output.items()}
        steps = int(np.floor(49 / .6))
        grid = torch.arange(steps + 1) * .6
        before = output['history_last_root_position'].reshape(1, 3)
        boundary = self.features.codec.decode_joint_configuration_pose(np.array([obs['reference_joints']]),
            np.array([self.frame.points(reference) @ BASIS]),
            root_rotation_matrices=np.array([self.frame.heading.T @ rotation_wxyz(obs['reference_root_quat'])]),
            joint_names=G1_JOINT_NAMES)
        # Relative motion: slide the clip on the ground plane so that its frame zero is the reference.
        planned = output['root_positions'].clone()
        offset = boundary['root_positions'][0] - planned[0]
        offset[1] = 0.
        planned += offset
        local, root_positions = _interpolate_motion(torch.cat((output['local_rot_mats'][:1], output['local_rot_mats'])),
            torch.cat((before + offset, planned)), grid + 1)
        sent_local, sent_root = blend_reference(local[1:], root_positions[1:], boundary['local_rot_mats'][0],
            boundary['root_positions'][0], np.arange(1, steps + 1)/50, self.handoff_seconds)
        actions = self.features.codec.encode(sent_local, sent_root, previous_root_position=boundary['root_positions'][0],
                                            hand_binary=torch.zeros(steps, 2)).numpy()
        actions[:, 9:38] = bounded_hinge_trajectory(sent_local, self.features.codec, self.fk.joint_limits,
                                                    obs['reference_joints'], self.joint_speed)
        planned_world = self.frame.world(planned.numpy())
        record = {'plan': self.plan_index, 'time': obs['time'], 'kind': 'walk', 'round': self.round.index, 'clip': w['clips'],
            'inference_s': elapsed, 'diffusion_steps': self.steps, 'arrive': arrive,
            'remaining_m': distance, 'reach_m': reach, 'control_steps': steps,
            'boundary_offset_m': float(offset.norm()),
            'planned_travel_m': float(np.linalg.norm(planned_world[-1, :2] - planned_world[0, :2])),
            'path_error_m': float(np.linalg.norm(planned_world[:, :2] - path, axis=1).max()),
            'end_error_m': float(np.linalg.norm(planned_world[-1, :2] - path[-1])),
            'measured_root': obs['root_pos'], 'reference_root': reference.tolist(), 'goal': w['goal'].tolist()}
        with (self.run / 'plans.jsonl').open('a') as f:
            f.write(json.dumps(record) + '\n')
        np.savez_compressed(self.run / f'plan-{self.plan_index:03d}.npz', actions=actions,
            planned_root_world=planned_world, path_world=path, conditions=values.numpy(), mask=mask.numpy())
        self.plan_index += 1
        w['clips'] += 1
        w['stopped'] = arrive
        return actions

    def at_stance(self, obs):
        c = self.cfg
        yaw = float(yaw_of(self.episode_heading.T @ rotation_wxyz(obs['root_quat'])))
        # Closer to the table than this, hanging fingers are already under its edge.
        return bool(np.linalg.norm(self.walk['goal'] - np.asarray(obs['root_pos'][:2])) <= c['stance_tolerance_m']
                    and abs(yaw) <= np.radians(c['stance_yaw_tolerance_deg'])
                    and c['table_edge_x_m'] - obs['root_pos'][0] >= c['stance_min_clearance_m'])

    def settled(self):
        """Both ankles down and the body nearly at rest over the last 0.3 s of measurements."""
        h = self.history[-15:]
        if len(h) < 15:
            return False
        dt = h[-1]['time'] - h[0]['time']
        root = np.linalg.norm(np.subtract(h[-1]['root_pos'], h[0]['root_pos'])) / dt
        feet = np.linalg.norm(np.subtract(h[-1]['foot_pos'], h[0]['foot_pos']), axis=1).max() / dt
        return bool(root < self.cfg['settled_root_speed_mps'] and feet < self.cfg['settled_foot_speed_mps']
                    and max(x[2] for x in h[-1]['foot_pos']) < self.cfg['settled_ankle_height_m'])

    def anchor(self, obs):
        """Start the standing backend at the measured stance and lay out this attempt's wrist path."""
        self.initialize(obs, heading=self.episode_heading)
        self.round.notes['anchor_reference_offset_m'] = float(np.linalg.norm(
            np.subtract(obs['reference_root_pos'], obs['root_pos'])))
        wrists, rotations = np.asarray(obs['wrist_pos']), np.asarray(obs['wrist_rot'])
        self.end_local = np.einsum('sji,sj->si', rotations, self.targets[:, 1] - self.targets[:, 0])
        self.rest = (wrists, rotations)
        self.bias = np.zeros((2, 3))
        c, r = self.cfg, self.round
        w = waypoints(r.box_pos, r.box_quat, obs['root_pos'][:2], c)
        self.way = w
        self.path = WristPath(obs['time'], wrists, rotations)
        r.notes['raise_end'] = self.path.to(w['via'], w['via_rotation'], c['raise_s'])
        r.notes['advance_end'] = self.path.to(w['pre'], w['rotation'], c['advance_s'])
        # The hands close where they arrive, open and beside the box; the squeeze comes after.
        r.event = {'id': f'round-{r.index}', 'positions': w['pre'].tolist(), 'rotations': w['rotation'].tolist(),
                   'deadline': r.notes['advance_end'] + c['gate_timeout_s']}
        r.notes.update(anchor_root=list(obs['root_pos']), opening_m=w['opening_m'], face_yaw_rad=w['face_yaw_rad'],
                       wrist_targets={k: w[k].tolist() for k in ('via', 'pre', 'squeeze', 'lift')})

    def correct(self, obs):
        """Outer loop on the wrists once they should be beside the box.

        Under a far reach SONIC gives way: the pelvis backs off and the wrists stop short of a
        reference the IK reaches exactly. The shortfall measured at each replan is added to what
        is commanded, bounded, until the gate has closed the hands; after that the hands push
        against the box and a position error is intended.
        """
        c, r = self.cfg, self.round
        if r.phase != 'advance' or obs['time'] < r.notes['advance_end'] - 1e-6:
            return
        wanted, _ = self.path(obs['time'])
        bias = self.bias + c['reach_feedback_gain'] * (wanted - np.asarray(obs['wrist_pos']))
        size = np.linalg.norm(bias, axis=1, keepdims=True)
        self.bias = bias * np.minimum(1., c['reach_feedback_max_m'] / np.maximum(size, 1e-9))
        r.notes['wrist_bias'] = self.bias.tolist()

    def goal(self, time):
        """Commanded wrist positions and rotations: the planned path plus the measured correction."""
        positions, rotations = self.path(time)
        return positions + self.bias, rotations

    def path_goals(self, elapsed):
        """Wrist and virtual hand-end goals in model coordinates at seconds since the anchor."""
        positions, rotations = zip(*(self.goal(self.start_time + e) for e in np.atleast_1d(elapsed)))
        positions, rotations = np.array(positions), np.array(rotations)
        ends = positions + np.einsum('tsij,sj->tsi', rotations, self.end_local)
        return self.frame.points(np.stack([positions, ends], axis=2)), self.frame.rotations(rotations)

    def aim(self, now):
        """Point the parent's keyframe at the end of the current piece, at most 1.5 s ahead."""
        self.arrival = min(self.path.piece_end(now), now + 1.5)
        wrists, rotations = self.goal(self.arrival)
        self.targets = np.stack([wrists, wrists + np.einsum('sij,sj->si', rotations, self.end_local)], axis=1)
        self.target_rot_world, self.target_rot_model = rotations, self.frame.rotations(rotations)
        self.target_info.update(mode='box-grasp', targets_world=self.targets.tolist(),
            wrist_rotation_world=rotations.tolist(), arrival_time=self.arrival)

    # ---- the round state machine -------------------------------------------------------
    def advance(self, samples):
        """Move between phases on the simulation clock and the measured gripper command."""
        obs = samples[-1]
        now, c, r = obs['time'], self.cfg, self.round
        closed = all(obs['gripper_command'])
        if r.phase == 'wait' and now >= r.latch_time + self.latch_delay/50 - 1e-6:
            if not r.graspable:
                return self.enter('idle', now)
            if self.stand_still:
                r.notes['stand_still'] = True
                self.anchor(obs)
                return self.enter('raise', now)
            # Walks end short of where they aim more often than past it, so they aim a little
            # further; the wrists are planned from wherever the robot actually stops.
            lead = self.episode_heading @ [c['walk_lead_m'], 0, 0]
            self.walk = {'goal': stance(r.box_pos, c) + lead[:2], 'clips': 0, 'stopped': True}
            r.notes.update(walk_start=list(obs['root_pos'][:2]), walk_goal=self.walk['goal'].tolist())
            if self.at_stance(obs):
                self.anchor(obs)
                return self.enter('raise', now)
            return self.enter('walk', now)
        if r.phase == 'idle' and now >= r.phase_time + c['idle_s']:
            return self.begin_round(obs)
        if r.phase == 'walk' and self.walk['clips'] and self.walk['stopped'] and (
                self.at_stance(obs) or self.walk['clips'] >= c['walk_max_clips']):
            r.notes.update(walk_clips=self.walk['clips'], walk_end=now)
            return self.enter('settle', now)
        if r.phase == 'settle' and ((now >= r.phase_time + c['settle_s'] and self.settled())
                                    or now >= r.phase_time + c['settle_timeout_s']):
            r.notes.update(settled=self.settled(), stance_error_m=float(np.linalg.norm(self.walk['goal'] - obs['root_pos'][:2])))
            self.anchor(obs)
            return self.enter('raise', now)
        if r.phase == 'raise' and now >= r.notes['raise_end'] - 1e-6:
            return self.enter('advance', now)
        if r.phase == 'advance':
            if closed:
                w = self.way
                r.notes['squeeze_start'] = max(now + c['grip_s'], r.notes['advance_end'])
                r.notes['squeeze_end'] = self.path.to(w['squeeze'], w['rotation'], c['squeeze_s'], start=r.notes['squeeze_start'])
                r.notes['lift_start'] = r.notes['squeeze_end'] + c['press_s']
                r.notes['lift_end'] = self.path.to(w['lift'], w['rotation'], c['lift_s'], start=r.notes['lift_start'])
                return self.enter('grip', now)
            if now >= r.event['deadline']:
                return self.release(now, 'gate_timeout')
        if r.phase == 'grip' and now >= r.notes['squeeze_start'] - 1e-6:
            return self.enter('squeeze', now)
        if r.phase == 'squeeze' and now >= r.notes['lift_start'] - 1e-6:
            return self.enter('lift', now)
        if r.phase == 'lift' and now >= r.notes['lift_end'] - 1e-6:
            return self.enter('hold', now)
        if r.phase == 'hold' and now >= r.phase_time + c['hold_s']:
            return self.release(now, 'no_success_after_hold')
        if r.phase == 'release' and now >= r.notes['release_end'] - 1e-6:
            return self.begin_round(obs)

    def release(self, now, reason):
        c, w, r = self.cfg, self.way, self.round
        opened, _ = self.path(now)
        opened[:, 1] = w['pre'][:, 1]
        self.path.to(opened, w['rotation'], c['open_s'], start=now)
        self.path.to(w['via'], w['via_rotation'], c['retreat_s'])
        r.notes.update(release_reason=reason, release_end=self.path.to(*self.rest, c['raise_s']))
        self.enter('release', now)

    def __call__(self, request):
        samples = request['observation']['oracle_history']
        if not samples:
            raise ValueError('Measured oracle history is required')
        obs = samples[-1]
        if self.episode_heading is None:
            self.begin_episode(samples[0])
        self.advance(samples)
        phase = self.round.phase
        if phase in STANDING:
            self.correct(obs)
            self.aim(obs['time'])
            response = super().__call__(request)
        else:
            self.remember(samples)
            if phase == 'walk' and len(self.history) >= 6:
                actions = self.walk_clip(obs, request)
            else:
                remaining = int(round((self.round.latch_time + self.latch_delay/50 - obs['time']) * 50))
                actions = self.hold(obs, min(25, remaining) if phase == 'wait' and remaining > 0 else 5)
            response = {'action_chunk': actions.tolist(), 'oracle_target': self.target_info}
        response['grasp'] = self.grasp_info()
        return response
